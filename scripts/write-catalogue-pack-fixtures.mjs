    "  CATALOGUE_PACK_ID,",
    "  CATALOGUE_RECORD_ID_PREFIX,",
    "  defineCataloguePackBadges,",
    "  catalogueRenderRecipeForSet,",
    '} from "./catalogue-pack-types.js";',
    'export type { CataloguePackBadgeFixture, CataloguePackBadgeRow } from "./catalogue-pack-types.js";',
