function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function stableQuotationIndex(definitionId, bankSize) {
  let accumulator = 0;
  for (const character of definitionId) {
    accumulator = (accumulator * 31 + character.codePointAt(0)) % 0xffffffff;
  }
  return accumulator % bankSize;
}

function stripQuotationPrefix(quotationId) {
  const prefix = "historic-quotation/";
  if (!quotationId.startsWith(prefix)) {
    throw new Error(
      `Designated quotation ${quotationId} does not carry the historic-quotation/ namespace; refresh the authoring records before writing the pack fixture.`,
    );
  }
  return quotationId.slice(prefix.length);
}

async function verifiedRow(entry) {
  const assetPath = path.join(assetsRoot, entry.assetDirectory, entry.sourceFileName);
  const bytes = await readFile(assetPath);
  const actual = sha256(bytes);
  if (actual !== entry.sourceSha256) {
    throw new Error(
      `Catalogue source ${entry.assetDirectory}/${entry.sourceFileName} hashes to ${actual}, but the authoring record declares ${entry.sourceSha256}; re-run the integrity writers before publishing the pack fixture.`,
    );
  }
  return [
    entry.definitionId,
    entry.title,
    entry.criterion,
    entry.description,
    entry.accessibleDescription,
    entry.sourceFileName,
    entry.sourceSha256,
    entry.defaultQuotationId,
    ...(entry.referenceUrl ? [entry.referenceUrl] : []),
  ];
}

function renderRows(rows) {
  return rows
    .map((row) => {
      const cells = row.map((cell) => `    ${JSON.stringify(cell)},`).join("\n");
      return `  [\n${cells}\n  ],`;
    })
    .join("\n");
}

function renderModule(exportName, rows, options) {
  const optionLines = [
    `    setId: ${JSON.stringify(options.setId)},`,
    `    assetDirectory: ${JSON.stringify(options.assetDirectory)},`,
    ...(options.regionId ? [`    regionId: ${JSON.stringify(options.regionId)},`] : []),
  ].join("\n");
  return [
    "// Generated by scripts/write-catalogue-pack-fixtures.mjs — do not edit by hand.",
    'import { defineCataloguePackBadges } from "./catalogue-pack-types.js";',
    "",
    `export const ${exportName} = defineCataloguePackBadges(`,
    "  [",
    renderRows(rows),
    "  ],",
    "  {",
    optionLines,
    "  },",
    ");",
    "",
  ].join("\n");
}

