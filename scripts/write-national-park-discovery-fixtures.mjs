import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import { createServer } from "vite";

const root = process.cwd();
const plans = [
  {
    outputName: "discovery-parks-a-g.ts",
    exportName: "discoveryParksAThroughG",
    includes: (slug) => /^[a-g]/u.test(slug),
  },
  {
    outputName: "discovery-parks-h-m.ts",
    exportName: "discoveryParksHThroughM",
    includes: (slug) => /^[h-m]/u.test(slug),
  },
  {
    outputName: "discovery-parks-n-z.ts",
    exportName: "discoveryParksNThroughZ",
    includes: (slug) => /^[n-z]/u.test(slug),
  },
];
const server = await createServer({
  root,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true },
});

try {
  const catalogue = await server.ssrLoadModule("/packages/catalogue-authoring/src/us-national-parks.ts");
  if (catalogue.usNationalParks.length !== 63) {
    throw new Error(
      `National-park discovery projection found ${catalogue.usNationalParks.length} studies; bind the exact 63-park edition before writing fixtures.`,
    );
  }
  const projected = catalogue.usNationalParks.filter(
    ({ definitionId }) => definitionId !== "visited-yosemite",
  );
  if (projected.length !== 62) {
    throw new Error(
      `National-park discovery projection found ${projected.length} non-starter studies; expected 62 after Yosemite deduplication.`,
    );
  }
  for (const plan of plans) {
    const rows = projected.filter(({ slug }) => plan.includes(slug));
    await writeProjection(plan, rows);
  }
} finally {
  await server.close();
}

async function writeProjection(plan, studies) {
  const outputFile = path.resolve(root, "packages/catalogue-fixtures/src", plan.outputName);
  const rows = studies.map((study) =>
    [
      "  [",
      `    ${JSON.stringify(study.definitionId)},`,
      `    ${JSON.stringify(study.shortName)},`,
      `    ${JSON.stringify(study.criterion)},`,
      `    ${JSON.stringify(study.locationLabel)},`,
      `    ${JSON.stringify(study.selectedSource.thumbnail.fileName)},`,
      `    ${JSON.stringify(study.selectedSource.accessibleDescription)},`,
      "  ],",
    ].join("\n"),
  );
  const source = [
    "// Generated by scripts/write-national-park-discovery-fixtures.mjs from the closed selected-study projection.",
    "// This Archive-safe file intentionally excludes prompts, source hashes, quotations, and authoring internals.",
    'import { defineSourceStudyBadges } from "./discovery-source-studies.js";',
    "",
    `export const ${plan.exportName} = defineSourceStudyBadges([`,
    rows.join("\n"),
    "]);",
    "",
  ].join("\n");
  await writeFile(outputFile, source, "utf8");
  process.stdout.write(
    `Projected ${studies.length} national-park studies into ${path.relative(root, outputFile)}.\n`,
  );
}
