import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import { createServer } from "vite";

const root = process.cwd();
const outputFile = path.resolve(root, "packages/catalogue-fixtures/src/discovery-us-states.ts");
const server = await createServer({
  root,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true },
});

try {
  const catalogue = await server.ssrLoadModule("/packages/catalogue-authoring/src/index.ts");
  if (catalogue.selectedUsStateStudies.length !== 50) {
    throw new Error(
      `State discovery projection found ${catalogue.selectedUsStateStudies.length} studies; bind the exact 50-state edition before writing the Archive-safe fixture.`,
    );
  }
  const rows = catalogue.selectedUsStateStudies.map((study) =>
    [
      "  [",
      `    ${JSON.stringify(study.definitionId)},`,
      `    ${JSON.stringify(study.title)},`,
      `    ${JSON.stringify(study.criterion)},`,
      `    ${JSON.stringify(study.contextLabel)},`,
      `    ${JSON.stringify(study.selectedSource.thumbnail.fileName)},`,
      `    ${JSON.stringify(study.selectedSource.accessibleDescription)},`,
      `    ${JSON.stringify(study.aliases)},`,
      "  ],",
    ].join("\n"),
  );
  const source = [
    "// Generated by scripts/write-us-state-discovery-fixture.mjs from the closed selected-study projection.",
    "// This Archive-safe file intentionally excludes prompts, source hashes, quotations, and authoring internals.",
    'import { defineSourceStudyBadges } from "./discovery-source-studies.js";',
    "",
    "export const discoveryUsStates = defineSourceStudyBadges(",
    "  [",
    rows.join("\n"),
    "  ],",
    '  { setId: "us-states", assetDirectory: "us-states" },',
    ");",
    "",
  ].join("\n");
  await writeFile(outputFile, source, "utf8");
  process.stdout.write(`Projected 50 U.S. state studies into ${path.relative(root, outputFile)}.\n`);
} finally {
  await server.close();
}
