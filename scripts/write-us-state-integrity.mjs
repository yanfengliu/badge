import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import { createServer } from "vite";

import { regenerateCatalogueThumbnails } from "./national-park-thumbnail-derivation.mjs";

const root = process.cwd();
const outputFile = path.resolve(root, "packages/catalogue-authoring/src/us-state-selected-source-hashes.ts");
const lineageOutputFile = path.resolve(
  root,
  "packages/catalogue-authoring/src/us-state-code-native-lineage.ts",
);
const assetsDirectory = path.resolve(root, "packages/catalogue-authoring/assets/us-states");
const thumbnailsDirectory = path.join(assetsDirectory, "thumbnails");
const rendererImplementationFiles = [
  "scripts/render-code-native-catalogue-art.mjs",
  "scripts/code-native-art/flat-raster.mjs",
  "scripts/code-native-art/png.mjs",
];

await regenerateCatalogueThumbnails({
  repositoryRoot: root,
  sourceDirectory: assetsDirectory,
  outputDirectory: thumbnailsDirectory,
  expectedCount: 50,
});

const server = await createServer({
  root,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true },
});

try {
  const [catalogue, codeNative, existingHashes, existingLineage] = await Promise.all([
    server.ssrLoadModule("/packages/catalogue-authoring/src/index.ts"),
    server.ssrLoadModule("/packages/catalogue-authoring/src/code-native-art-recipes.ts"),
    server.ssrLoadModule("/packages/catalogue-authoring/src/us-state-selected-source-hashes.ts"),
    loadOptionalModule(
      server,
      lineageOutputFile,
      "/packages/catalogue-authoring/src/us-state-code-native-lineage.ts",
    ),
  ]);
  const projectsByDefinitionId = new Map(
    catalogue.usStateCampaign.map((project) => [project.definitionId, project]),
  );
  const sourceHashes = {};
  const promptHashes = {};
  const thumbnailHashes = {};
  const lineage = {};
  const rendererImplementationSha256 = await sha256Files(rendererImplementationFiles);
  for (const state of catalogue.usStates) {
    const sourceFile = path.join(assetsDirectory, `${state.slug}.jpg`);
    const sourceBytes = await readBounded(sourceFile, 256 * 1024, "selected source study");
    const project = projectsByDefinitionId.get(state.definitionId);
    const primary = project?.candidates.find(
      (candidate) => candidate.candidateKey === project.primaryCandidateKey,
    );
    if (!project || !primary) {
      throw new Error(
        `U.S. state integrity found no primary prompt for ${state.slug}; repair its campaign before refreshing hashes.`,
      );
    }
    const prompt = catalogue.compileCandidatePrompt(project.brief, primary).prompt;
    const promptSha256 = sha256(new TextEncoder().encode(prompt));
    const recipe = codeNative.findCodeNativeArtRecipe("us-states", state.slug);
    if (!recipe) {
      throw new Error(
        `U.S. state integrity found no code-native replacement recipe for us-states/${state.slug}; register every reviewed state design before refreshing lineage.`,
      );
    }
    const priorLineage = existingLineage?.usStateCodeNativeLineage?.[state.slug];
    const canonicalPromptSha256 =
      priorLineage?.canonicalPromptSha256 ?? existingHashes.usStatePromptHashes[state.slug];
    if (!canonicalPromptSha256 || canonicalPromptSha256 !== promptSha256) {
      throw new Error(
        `U.S. state integrity refused to change the original selected prompt for ${state.slug}; preserve its v1 generation association or record an explicit successor lineage.`,
      );
    }
    const thumbnailFile = path.join(thumbnailsDirectory, `${state.slug}.jpg`);
    const thumbnailBytes = await readBounded(thumbnailFile, 16 * 1024, "list thumbnail");
    sourceHashes[state.slug] = sha256(sourceBytes);
    promptHashes[state.slug] = promptSha256;
    thumbnailHashes[state.slug] = sha256(thumbnailBytes);
    lineage[state.slug] = {
      canonicalSourceSha256:
        priorLineage?.canonicalSourceSha256 ?? existingHashes.usStateSourceHashes[state.slug],
      canonicalPromptSha256,
      designBriefSha256: sha256(new TextEncoder().encode(codeNative.serializeCodeNativeArtRecipe(recipe))),
      rendererImplementationSha256,
    };
  }

  const source = [
    "// Generated by scripts/write-us-state-integrity.mjs after visual review and asset normalization.",
    "// Digests bind selected bytes and list derivatives to the exact canonical primary prompt.",
    "// They prove association and immutability, not historical causation of a model call.",
    `export const usStateSourceHashes: Readonly<Record<string, string>> = ${formatHashRecord(sourceHashes)};`,
    "",
    `export const usStatePromptHashes: Readonly<Record<string, string>> = ${formatHashRecord(promptHashes)};`,
    "",
    `export const usStateThumbnailHashes: Readonly<Record<string, string>> = ${formatHashRecord(thumbnailHashes)};`,
    "",
  ].join("\n");
  await writeFile(outputFile, source, "utf8");
  const lineageSource = [
    "// Generated by scripts/write-us-state-integrity.mjs before and after reviewed code-native replacement promotion.",
    'import type { SelectedSourceCodeNativeLineage } from "./types";',
    "",
    "export const usStateCodeNativeLineage: Readonly<",
    "  Record<string, SelectedSourceCodeNativeLineage>",
    `> = ${formatLineageRecord(lineage)};`,
    "",
  ].join("\n");
  await writeFile(lineageOutputFile, lineageSource, "utf8");
  process.stdout.write(
    `Bound ${Object.keys(sourceHashes).length} U.S. state studies to source, thumbnail, and canonical-prompt SHA-256 digests.\n`,
  );
} finally {
  await server.close();
}

async function readBounded(file, maximumBytes, kind) {
  let bytes;
  try {
    bytes = await readFile(file);
  } catch (error) {
    throw new Error(`U.S. state integrity could not read ${kind} ${file}; rebuild the complete edition.`, {
      cause: error,
    });
  }
  if (bytes.byteLength > maximumBytes) {
    throw new Error(
      `U.S. state integrity rejected ${kind} ${file} at ${bytes.byteLength} bytes; keep it at or below ${maximumBytes} bytes.`,
    );
  }
  return bytes;
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function formatHashRecord(record) {
  const entries = Object.entries(record).map(([key, value]) => {
    const formattedKey = /^[A-Za-z_$][\w$]*$/u.test(key) ? key : JSON.stringify(key);
    return `  ${formattedKey}: ${JSON.stringify(value)},`;
  });
  return `{\n${entries.join("\n")}\n}`;
}

function formatLineageRecord(record) {
  const entries = Object.entries(record).map(
    ([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`,
  );
  return `{\n${entries.join("\n")}\n}`;
}

async function loadOptionalModule(server, file, moduleId) {
  try {
    await readFile(file);
  } catch (error) {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  }
  return server.ssrLoadModule(moduleId);
}

async function sha256Files(relativeFiles) {
  const hash = createHash("sha256");
  for (const relativeFile of relativeFiles) {
    hash.update(relativeFile, "utf8");
    hash.update("\0", "utf8");
    hash.update(await readFile(path.resolve(root, relativeFile)));
    hash.update("\0", "utf8");
  }
  return hash.digest("hex");
}
